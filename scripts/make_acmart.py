def front_and_body(text: str) -> tuple[str, str]:
    """Split the manuscript into its abstract and everything after the front matter."""
    abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", text, re.DOTALL)
    if not abstract:
        raise SystemExit("no abstract found in the manuscript")
    body = text[abstract.end():]
    inner = abstract.group(1)
    inner = re.sub(r"\\bigskip\s*\\noindent\\textbf\{Keywords:\}.*", "", inner, flags=re.DOTALL)
    inner = inner.replace("\\noindent", "").strip()
    return "\\begin{abstract}\n" + inner + "\n\\end{abstract}\n", body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper", default="paper/main.tex")
    parser.add_argument("--output", default="paper/tops")
    parser.add_argument("--supplement", action="store_true",
                        help="split the appendices into supplement.tex for a page limit")
    arguments = parser.parse_args()

    source = Path(arguments.paper)
    output = Path(arguments.output)
    output.mkdir(parents=True, exist_ok=True)
    text = source.read_text()
    abstract, body = front_and_body(text)

    # acmart defines proposition, corollary, lemma, definition and remark itself
    body = re.sub(r"\\newtheorem\{[^}]+\}(\[[^]]+\])?\{[^}]+\}\n", "", body)
    body = re.sub(r"\\theoremstyle\{[^}]+\}\n", "", body)
    body = body.replace("\\bibliographystyle{plainnat}\n", "")
    supplement = ""
    if arguments.supplement:
        marker = "\\appendix"
        if marker not in body:
            raise SystemExit("no appendix marker found in the manuscript")
        body, appendices = body.split(marker, 1)
        bibliography = ""
        if "\\begin{thebibliography}" in appendices:
            appendices, bibliography = appendices.split("\\begin{thebibliography}", 1)
            bibliography = "\\begin{thebibliography}" + bibliography
        body = body + bibliography
        supplement = (PREAMBLE.replace("%%ABSTRACT%%", "").replace(
            "\\title{Quantitative risk assessment",
            "\\title{Supplementary material: quantitative risk assessment")
            + "\\appendix" + appendices + "\n\\end{document}\n")

    written = PREAMBLE.replace("%%ABSTRACT%%", abstract) + body
    if supplement:
        written = written.rstrip() + "\n\\end{document}\n"
        (output / "supplement.tex").write_text(supplement)
    (output / "main.tex").write_text(written)

    for folder in ("generated", "figures", "diagrams"):
        target = output / folder
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(source.parent / folder, target)
    for auxiliary in source.parent.glob("diagram_*.tex"):
        shutil.copy2(auxiliary, output / auxiliary.name)
    shutil.copy2(source.parent / "neural_section.tex", output / "neural_section.tex")
    shutil.copy2(source.parent / "neural_appendix.tex", output / "neural_appendix.tex")
    shutil.copy2(source.parent / "sentry_r_section.tex", output / "sentry_r_section.tex")
    shutil.copy2(source.parent / "sentry_r_appendix.tex", output / "sentry_r_appendix.tex")
    print(f"wrote {output / 'main.tex'} with auxiliary figures and text copied alongside")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
