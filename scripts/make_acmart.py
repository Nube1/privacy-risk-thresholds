"""Generate the ACM TOPS submission from the manuscript, so there is one source.

The article version in ``paper/main.tex`` stays the working copy. This script
rewrites its front matter for the current ACM ``acmart`` class and leaves the body,
the generated tables and the bibliography untouched, so a change to the paper
reaches the submission by rerunning this rather than by editing a second file.

    python scripts/make_acmart.py --paper paper/main.tex --output paper/tops

Compile the result from its own directory. Add ``anonymous`` to the class options
if the journal asks for a blinded review copy.
"""
